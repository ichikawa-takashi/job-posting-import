/**
 * 転職者に見せる呼び名
 * ------------------------------------------------------------
 * 上の表の {DESK} が、ここのどちらかに置き換わります。
 *
 *   construction … 建築・建設・プラント系の求人
 *   realestate   … 不動産系の求人
 *
 * 求人ごとに決め方は3段階です。
 *   1. JSONに "displayTerm": "construction" と書いてあれば、それに従う
 *   2. 書いていなければ、本文の語から自動で判定する（desk_word_for）
 *   3. 判定できなければ realestate（不動産事務）
 *
 * 管理画面・一覧ページ・カテゴリは、どちらの場合も「施工管理」のままです。
 * ------------------------------------------------------------
 */
const DESK_TERMS = [
    'construction' => '建設事務',
    'realestate'   => '不動産事務',
];

const DESK_DEFAULT = 'realestate';

/** 自動判定に使う語。どちら寄りの求人かを数えます。 */
const DESK_HINTS = [
    'construction' => ['建築', '建設', 'プラント', 'ゼネコン', '土木', '内装', '設備工事',
                       '現場監督', '施工図', '建築士', '工事'],
    'realestate'   => ['不動産', '賃貸', '売買', '仲介', '管理物件', '入居', 'マンション管理',
                       '宅地建物取引士', '宅建'],
];

/**
 * この求人を、転職者にはどう呼ぶか決める。
 * 戻り値は「建設事務」または「不動産事務」。
 */
function desk_word_for(array $job): string
{
    $key = (string)($job['displayTerm'] ?? '');
    if (isset(DESK_TERMS[$key])) {
        return DESK_TERMS[$key];          // JSONで指定されていればそれに従う
    }

    // 指定が無ければ本文から推測する
    $text = json_encode($job, JSON_UNESCAPED_UNICODE);
    $score = ['construction' => 0, 'realestate' => 0];
    foreach (DESK_HINTS as $k => $words) {
        foreach ($words as $w) {
            $score[$k] += substr_count($text, $w);
        }
    }
    if ($score['construction'] === $score['realestate']) {
        return DESK_TERMS[DESK_DEFAULT];
    }
    return DESK_TERMS[$score['construction'] > $score['realestate']
        ? 'construction' : 'realestate'];
}

/**
 * 求人票データの文字列すべてに言い換えを適用する。
 * category と id は対象外（一覧ページと管理画面で使うため）。
 *
 * 呼び方：$job = apply_display_terms($job);
 */
function apply_display_terms($v, string $key = '')
{
    // 最初の呼び出し（求人まるごと）で、この求人の呼び名を決める
    if (is_array($v) && isset($v['id'])) {
        $table = [];
        $desk  = desk_word_for($v);
        foreach (DISPLAY_TERMS as $from => $to) {
            $table[$from] = str_replace('{DESK}', $desk, $to);
        }
        return terms_walk($v, $table);
    }
    // 求人以外を渡された場合は、既定の呼び名で処理する
    $table = [];
    foreach (DISPLAY_TERMS as $from => $to) {
        $table[$from] = str_replace('{DESK}', DESK_TERMS[DESK_DEFAULT], $to);
    }
    return terms_walk($v, $table);
}

/** 用意した置き換え表で、中身をすべて辿って差し替える */
function terms_walk($v, array $table)
{
    // 社内用の項目は触らない
    static $skip = ['category', 'id', 'status', 'fee', 'updated', 'displayTerm'];

    if (is_string($v)) {
        return strtr($v, $table);
    }
    if (is_array($v)) {
        $out = [];
        foreach ($v as $k => $x) {
            $out[$k] = (is_string($k) && in_array($k, $skip, true))
                ? $x
                : terms_walk($x, $table);
        }
        return $out;
    }
    return $v;
}
